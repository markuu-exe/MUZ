// Generates src/styles/theme.css: Tailwind palettes as CSS variables, with an
// inverted scale for light mode (50<->950, 100<->900, ...). Run: node scripts/generate-theme-css.mjs
import { writeFileSync } from 'node:fs';
import colors from 'tailwindcss/colors.js';

export const THEMED = ['slate', 'violet', 'amber', 'rose', 'emerald', 'cyan', 'sky', 'fuchsia', 'purple', 'red', 'teal', 'orange', 'indigo'];
const SHADES = ['50', '100', '200', '300', '400', '500', '600', '700', '800', '900', '950'];
const rgb = (hex) => {
  const h = hex.replace('#', '');
  return [0, 2, 4].map((i) => parseInt(h.slice(i, i + 2), 16)).join(' ');
};

let dark = '';
let light = '';
for (const name of THEMED) {
  SHADES.forEach((shade, i) => {
    dark += `  --c-${name}-${shade}: ${rgb(colors[name][shade])};\n`;
    light += `  --c-${name}-${shade}: ${rgb(colors[name][SHADES[SHADES.length - 1 - i]])};\n`;
  });
}
const css = `/* GENERATED by scripts/generate-theme-css.mjs. Do not edit by hand. */
/* Dark is the default design; light mode inverts each palette so pairings like
   "300 text on 950 background" become "700 text on 50 background". */
:root,
[data-theme='dark'] {
${dark}  --c-white: 255 255 255;
  --c-black: 0 0 0;
  --c-muz-bg: 7 11 20;
  --c-muz-panel: 16 24 39;
  --c-muz-panel-strong: 18 29 46;
  --c-muz-sidebar: 12 18 32;
  --c-muz-accent: 115 224 169;
  --c-muz-accent-strong: 84 209 140;
  --c-muz-text: 237 242 255;
  --c-muz-muted: 154 168 189;
  color-scheme: dark;
}

[data-theme='light'] {
${light}  --c-white: 15 23 42;
  --c-black: 255 255 255;
  --c-muz-bg: 241 245 249;
  --c-muz-panel: 255 255 255;
  --c-muz-panel-strong: 248 250 252;
  --c-muz-sidebar: 255 255 255;
  --c-muz-accent: 22 163 74;
  --c-muz-accent-strong: 21 128 61;
  --c-muz-text: 15 23 42;
  --c-muz-muted: 71 85 105;
  color-scheme: light;
}
`;
writeFileSync(new URL('../src/styles/theme.css', import.meta.url), css);
console.log('wrote src/styles/theme.css');
